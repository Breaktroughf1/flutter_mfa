const commonPasswordsCount = $_count;

/// Sorted, front-coded list: see tool/gen_common_passwords.dart.
const commonPasswordsFrontCoded = r\'\'\'
$data\'\'\';
''');
  stdout.writeln('wrote $_out (${words.length} entries, ${data.length} chars)');
}
