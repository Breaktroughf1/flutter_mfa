// Generates packages/flutter_mfa_core/lib/src/backup/common_passwords.g.dart
// from zxcvbn's frequency lists (MIT, Dan Wheeler and Dropbox, Inc.).
//
//   npm pack zxcvbn@4.4.2 && tar xzf zxcvbn-4.4.2.tgz
//   dart run tool/gen_common_passwords.dart package/lib/frequency_lists.js
//
// The output keeps the 10 000 most frequent entries of the `passwords` list,
// sorted and front-coded (each line: one character giving the length of the
// prefix shared with the previous line, as 'a' + length, then the rest).
import 'dart:io';

const _count = 10000;
const _out = 'packages/flutter_mfa_core/lib/src/backup/common_passwords.g.dart';

void main(List<String> args) {
  if (args.length != 1) {
    stderr.writeln(
      'usage: dart run tool/gen_common_passwords.dart <frequency_lists.js>',
    );
    exit(64);
  }
  final source = File(args.single).readAsStringSync();
  final match = RegExp(r'passwords:\s*"([^"]*)"').firstMatch(source);
  if (match == null) throw StateError('no passwords list in ${args.single}');
  final all = match.group(1)!.split(',');
  final words = all.take(_count).toSet().toList()..sort();
  if (words.length != _count) {
    throw StateError('expected $_count unique entries');
  }
  for (final w in words) {
    if (w.isEmpty || w.codeUnits.any((c) => c < 0x21 || c > 0x7e)) {
      throw StateError('unexpected entry in the source list');
    }
  }
  final lines = <String>[];
  var previous = '';
  for (final w in words) {
    var shared = 0;
    while (shared < w.length &&
        shared < previous.length &&
        shared < 25 &&
        w.codeUnitAt(shared) == previous.codeUnitAt(shared)) {
      shared++;
    }
    lines.add(String.fromCharCode(0x61 + shared) + w.substring(shared));
    previous = w;
  }
  final data = lines.join('\n');
  // Decode the output again and check it gives back exactly the source words.
  final decoded = <String>[];
  var last = '';
  for (final line in lines) {
    last = last.substring(0, line.codeUnitAt(0) - 0x61) + line.substring(1);
    decoded.add(last);
  }
  if (decoded.join('\n') != words.join('\n')) {
    throw StateError('front coding does not round-trip');
  }
  // A raw string cannot contain the delimiter; the alphabet is printable ASCII.
  if (data.contains("'''")) throw StateError('delimiter in data');
  File(_out).writeAsStringSync('''
// GENERATED by tool/gen_common_passwords.dart. Do not edit.
//
// The 10 000 most common passwords from zxcvbn 4.4.2 (frequency_lists.js),
// sorted and front-coded. Used only to reject backup passphrases.
